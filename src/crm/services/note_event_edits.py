"""Narrow edit authority: newer human source for an unchanged owned callback.

No historical inference, email rewrite, closed-task reopening or human/provider
edit overwrite. Provider projection retains its own etag/ownership checks.
"""
from sqlalchemy import select, true
from datetime import UTC, datetime
from uuid import UUID
from src.crm.persistence.models import AgentWork, Activity


def update_owned_callback(session, task, action, source, row):
    if not (row.payload.get('note_event_v1') is True
            and task is not None and task.task_type == action.task_type == 'call'
            and task.status == 'open' and task.source_rule == 'head_of_sales_note'
            and task.version == action.expected_task_version
            and task.lead_id == row.lead_id):
        return False
    prior=session.scalar(select(AgentWork).where(
        AgentWork.workspace_id==row.workspace_id, AgentWork.lead_id==row.lead_id,
        AgentWork.kind=='call_followup', AgentWork.status=='completed',
        AgentWork.result['tasks'].contains([{'task_id':str(task.id)}]),
        AgentWork.payload['activity_id'].astext==source['supersedes_activity_id'] if source.get('supersedes_activity_id') else true()
    ).order_by(AgentWork.updated_at.desc(),AgentWork.id.desc()).limit(1))
    if prior is None:
        return False
    try:
        origin=session.get(Activity,UUID(prior.payload['activity_id']))
    except (ValueError,KeyError,TypeError):
        return False
    if not (origin and origin.workspace_id==row.workspace_id and origin.lead_id==row.lead_id
            and origin.occurred_at < datetime.fromisoformat(source['occurred_at'])):
        return False
    proofs=[ref for ref in (prior.result or {}).get('tasks',[]) if ref.get('task_id')==str(task.id)]
    if len(proofs)!=1:
        return False
    proof=proofs[0]
    if proof.get('edit_fence') is not None:
        unchanged=proof['edit_fence']=={'version':task.version,'title':task.title,
            'due_at':task.due_at.astimezone(UTC).isoformat()}
    else:
        # Pre-event callbacks have no new fence. Their ORIGINAL note receipt
        # pins the calendar work version; never consult the latest calendar row
        # which could have been generated by a subsequent manual task edit.
        try:
            calendar=session.get(AgentWork,UUID(proof['calendar_work_id']))
        except (ValueError,KeyError,TypeError):
            return False
        unchanged=bool(calendar and calendar.workspace_id==row.workspace_id
            and calendar.task_id==task.id and calendar.kind=='calendar_callback'
            and calendar.payload.get('task_version')==task.version)
    if not unchanged:
        return False
    if (source.get('supersedes_activity_id') and task.due_at==action.due_at
            and proof.get('intent_quote',action.quote)==action.quote):
        # Annotation of this same source/intent is not another callback. Its
        # original provider description remains an immutable historical record.
        return 'annotation'
    task.title=action.title
    task.due_at=action.due_at
    # Preserve one current CRM obligation, with prior state in immutable note
    # results/audits. New source identity creates a NEW Calendar occurrence.
    task.version += 1

    return 'new_occurrence'
